"""SoundStack end-to-end test (Playwright + headless Chrome at iPhone size 390x844).
Run: python tests/test.py [url]   (serve the folder first, e.g. python -m http.server 8822)"""
import sys, os, time
from playwright.sync_api import sync_playwright
URL = sys.argv[1] if len(sys.argv) > 1 else "http://127.0.0.1:8822/"
HERE = os.path.dirname(os.path.abspath(__file__)); SHOTS = os.path.join(HERE, "..", "screenshots")
ok, bad = [], []
def check(c, m): (ok if c else bad).append(m); print(("PASS " if c else "FAIL ") + m, flush=True)
with sync_playwright() as p:
    b = p.chromium.launch(executable_path="/usr/bin/google-chrome", args=["--no-sandbox", "--autoplay-policy=user-gesture-required"])
    ctx = b.new_context(viewport={"width": 390, "height": 844}, device_scale_factor=2, is_mobile=True, has_touch=True)
    pg = ctx.new_page(); errs = []
    pg.on("pageerror", lambda e: errs.append("pageerror: " + str(e)))
    pg.on("console", lambda m: m.type == "error" and errs.append("console: " + m.text))
    pg.goto(URL); pg.wait_for_function("() => window.SS && SS.lib.length > 0"); pg.wait_for_timeout(1800)
    n = pg.evaluate("() => SS.lib.length")
    check(n == 9, f"loads with {n} bundled Suno songs")
    check(pg.inner_text("#title") == "Light Goes Dark", f"Light Goes Dark is the featured first song ({pg.inner_text('#title')})")
    imgs = pg.evaluate("() => [...document.querySelectorAll('.case img')].map(i => i.complete && i.naturalWidth > 0)")
    check(len(imgs) >= 12 and all(imgs), f"3D stack shows {len(imgs)} cases, every real cover image loaded")
    tags = pg.evaluate("async () => { const r = await fetch('songs/light-goes-dark.mp3', {headers: {Range: 'bytes=0-524287'}}); const t = await SS.readID3(await r.blob()); return [t.title, t.artist, t.picture && t.picture.size, t.picture && t.picture.type]; }")
    check(tags[0] == "Light Goes Dark" and tags[1] == "Odisus" and tags[2] and tags[2] > 10000, f"JS ID3 reader pulls title/artist/embedded cover from the bundled MP3 {tags}")
    pg.screenshot(path=os.path.join(SHOTS, "1-home.png"))
    # play
    pg.click("#btn-play"); pg.wait_for_timeout(1500)
    st = pg.evaluate("() => [SS.au.paused, SS.au.currentTime, SS.au.src.split('/').pop()]")
    check(not st[0] and st[1] > 0.3, f"Play starts real audio ({st[2]} at {st[1]:.1f}s)")
    ms = pg.evaluate("() => navigator.mediaSession.metadata && [navigator.mediaSession.metadata.title, navigator.mediaSession.metadata.artwork.length, navigator.mediaSession.playbackState]")
    check(ms and ms[0] == "Light Goes Dark" and ms[1] == 1 and ms[2] == "playing", f"lock-screen Media Session set {ms}")
    check(pg.evaluate("() => document.querySelector('#badge').classList.contains('show')") and "Now playing" in pg.inner_text("#badge"), "♪ Now playing badge shows")
    # next: shuffle animation + background color
    acc0 = pg.evaluate("() => getComputedStyle(document.documentElement).getPropertyValue('--accent').trim()")
    tf0 = pg.evaluate("() => getComputedStyle(document.querySelector('.case.front')).transform")
    pg.click("#btn-next"); pg.wait_for_timeout(120)
    mid = pg.evaluate("() => document.querySelectorAll('.case').length")
    pg.wait_for_timeout(900)
    t1 = pg.inner_text("#title"); acc1 = pg.evaluate("() => getComputedStyle(document.documentElement).getPropertyValue('--accent').trim()")
    tf1 = pg.evaluate("() => getComputedStyle(document.querySelector('.case.front')).transform")
    check(t1 != "Light Goes Dark" and mid > 16, f"Next shuffles the stack (old front card animating out, {mid} cases mid-move) -> {t1}")
    check(acc0 != acc1, f"background glow color changes {acc0} -> {acc1}")
    check(tf0 == tf1, "new front card settles exactly in the front slot")
    check(not pg.evaluate("() => SS.au.paused") and pg.evaluate("() => SS.au.src.includes(SS.cur().url.split('/').pop())"), "the next song plays")
    # swipe (drag the front card down-left = next, up-right = previous)
    tA = pg.inner_text("#title")
    pg.mouse.move(150, 500); pg.mouse.down(); pg.mouse.move(110, 560, steps=6); pg.mouse.move(80, 610, steps=6); pg.mouse.up(); pg.wait_for_timeout(900)
    tB = pg.inner_text("#title")
    pg.mouse.move(120, 560); pg.mouse.down(); pg.mouse.move(180, 480, steps=8); pg.mouse.up(); pg.wait_for_timeout(900)
    tC = pg.inner_text("#title")
    check(tB != tA and tC == tA, f"swipe down-left -> next ({tB}), swipe up-right -> back ({tC})")
    # Pick for me
    pg.click("#btn-pick"); pg.wait_for_timeout(250)
    pg.evaluate("() => { window.__fr = []; let l = performance.now(); (function f(t) { window.__fr.push(t - l); l = t; if (SS.picking) requestAnimationFrame(f); })(l); return 1; }")
    check(pg.inner_text("#pick-t") == "Picking…" and pg.evaluate("() => SS.picking"), "button changes to Picking… and the stack spins")
    pg.wait_for_timeout(1500); pg.screenshot(path=os.path.join(SHOTS, "2-picking.png"))
    pg.wait_for_function("() => !SS.picking", timeout=15000); pg.wait_for_timeout(500)
    landed = pg.evaluate("() => [document.querySelector('#badge-t').textContent, document.querySelector('#pick-t').textContent, SS.au.paused, SS.cur().title, document.querySelector('.case.front').dataset.title]")
    check("Tonight" in landed[0] and landed[1] == "Pick for me" and not landed[2] and landed[3] == landed[4], f"Pick lands on {landed[3]} with a ✦ Tonight's pick badge and plays it")
    pg.screenshot(path=os.path.join(SHOTS, "3-tonights-pick.png"))
    fr = [f for f in pg.evaluate("() => window.__fr.slice(5)") if f < 120]; avg = sum(fr) / len(fr); slow = sum(1 for f in fr if f > 34)
    check(avg < 19, f"spin animation frame rate ~{1000/avg:.0f} fps (headless software rendering, {slow} frames >34ms of {len(fr)}; the mid-spin screenshot stall is excluded)")
    # scrubber seek
    box = pg.locator("#wave").bounding_box(); pg.mouse.click(box["x"] + box["width"] * .5, box["y"] + box["height"] / 2); pg.wait_for_timeout(400)
    s = pg.evaluate("() => [SS.au.currentTime, SS.au.duration]")
    check(abs(s[0] - s[1] / 2) < 4, f"tapping the middle of the waveform seeks to {s[0]:.0f}s of {s[1]:.0f}s")
    # favorite, shuffle, repeat
    pg.click("#btn-fav"); check(pg.evaluate("() => document.querySelector('#btn-fav').classList.contains('on')"), "♥ favorite toggles on")
    pg.click("#btn-shuffle"); pg.wait_for_timeout(600); check(pg.evaluate("() => document.querySelector('#btn-shuffle').classList.contains('on')") and pg.inner_text("#title") == landed[3], "shuffle on keeps the current song in front")
    pg.click("#btn-repeat"); check(pg.evaluate("() => document.querySelector('#btn-repeat').classList.contains('one')"), "repeat cycles to repeat-one")
    pg.click("#btn-repeat"); pg.click("#btn-repeat"); pg.click("#btn-shuffle"); pg.wait_for_timeout(500)
    # add songs from the phone (MP3 with embedded art + one without)
    n0 = pg.evaluate("() => SS.lib.length")
    pg.set_input_files("#file", [os.path.join(HERE, "fixtures", "test-upload.mp3"), os.path.join(HERE, "fixtures", "no_art_song.mp3")])
    pg.wait_for_function(f"() => SS.lib.length === {n0 + 2}", timeout=15000); pg.wait_for_timeout(600)
    add = pg.evaluate("() => SS.lib.slice(-2).map(s => [s.title, s.artist, s.style, s.cover.slice(0,5), s.color, Math.round(s.duration), !!s.peaks])")
    check(add[0][0] == "Test Upload Song" and add[0][1] == "Odisus" and add[0][3] == "blob:", f"added MP3: title/artist read from ID3, embedded cover used {add[0]}")
    c = add[0][4]; r, g, bl = int(c[1:3], 16), int(c[3:5], 16), int(c[5:7], 16)
    check(r > 150 and g < 90, f"glow color comes from the embedded (red) cover art: {c}")
    check(add[1][0] == "no art song" and add[1][3] == "blob:" and add[1][6], f"MP3 without art gets a generated cover + waveform {add[1]}")
    check(pg.inner_text("#title") == "no art song", "stack jumps to the newly added song")
    if pg.evaluate("() => SS.au.paused"): pg.click("#btn-play")
    pg.wait_for_timeout(1200)
    check(not pg.evaluate("() => SS.au.paused") and pg.evaluate("() => SS.au.currentTime") > 0.3 and pg.evaluate("() => SS.au.src.startsWith('blob:')"), "added song plays from the phone's storage")
    pg.click("#btn-menu"); pg.wait_for_timeout(500)
    check(pg.locator("#list li").count() == n0 + 2, "library sheet lists every song")
    pg.screenshot(path=os.path.join(SHOTS, "4-library.png"))
    pg.fill("#q", "test upload"); pg.wait_for_timeout(200)
    check(pg.locator("#list li[data-i]").count() == 1, "search filters the list")
    pg.click("#list li[data-i] .lt"); pg.wait_for_timeout(900)
    check(pg.inner_text("#title") == "Test Upload Song" and not pg.evaluate("() => SS.au.paused"), "tapping a search result plays it")
    # persistence + offline
    pg.reload(); pg.wait_for_function("() => window.SS && SS.lib.length > 0"); pg.wait_for_timeout(1500)
    check(pg.evaluate("() => SS.lib.length") == n0 + 2, "added songs are still there after reopening (IndexedDB)")
    pg.wait_for_function("() => navigator.serviceWorker.controller", timeout=10000)
    ctx.set_offline(True); pg.reload(); pg.wait_for_function("() => window.SS && SS.lib.length > 0", timeout=10000); pg.wait_for_timeout(800)
    imgs = pg.evaluate("() => [...document.querySelectorAll('.case img')].every(i => i.complete && i.naturalWidth > 0)")
    check(imgs and pg.inner_text("#title") != "", "opens offline with covers (service worker)")
    ctx.set_offline(False)
    check(not errs, f"no console errors {errs[:5]}")
    b.close()
print(f"\n{len(ok)} passed, {len(bad)} failed"); sys.exit(1 if bad else 0)
